/**
 * Even Hub store-icon helpers.
 * Spec: 24×24, 1-bit, every lit pixel is a 2×2 block (12×12 detail budget).
 * @see https://hub.evenrealities.com/docs/build/design-guidelines#the-store-icon
 */

export type StoreIconRows = readonly string[]

export type StoreIconRect = { x: number; y: number; w: number; h: number }

export function assertStoreIconRows(rows: StoreIconRows, name = 'icon'): void {
  if (rows.length !== 12) {
    throw new Error(`${name}: expected 12 rows, got ${rows.length}`)
  }
  for (let i = 0; i < rows.length; i++) {
    const row = rows[i] ?? ''
    if (row.length !== 12) {
      throw new Error(`${name} row ${i}: expected length 12, got ${row.length}`)
    }
    if (!/^[.#]+$/.test(row)) {
      throw new Error(`${name} row ${i}: only . and # allowed`)
    }
  }
}

/** Expand 12×12 `#` blocks into axis-aligned 2×2 rects on the 24×24 grid. */
export function storeIconRects(rows: StoreIconRows): StoreIconRect[] {
  assertStoreIconRows(rows)
  const rects: StoreIconRect[] = []
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y] ?? ''
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue
      rects.push({ x: x * 2, y: y * 2, w: 2, h: 2 })
    }
  }
  return rects
}

export function createStoreIconSvg(rows: StoreIconRows): SVGSVGElement {
  const rects = storeIconRects(rows)
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg')
  svg.setAttribute('viewBox', '0 0 24 24')
  svg.setAttribute('width', '24')
  svg.setAttribute('height', '24')
  svg.setAttribute('aria-hidden', 'true')
  svg.setAttribute('shape-rendering', 'crispEdges')
  svg.classList.add('icon', 'icon--pixel')
  for (const r of rects) {
    const rect = document.createElementNS('http://www.w3.org/2000/svg', 'rect')
    rect.setAttribute('x', String(r.x))
    rect.setAttribute('y', String(r.y))
    rect.setAttribute('width', String(r.w))
    rect.setAttribute('height', String(r.h))
    rect.setAttribute('fill', 'currentColor')
    svg.append(rect)
  }
  return svg
}

